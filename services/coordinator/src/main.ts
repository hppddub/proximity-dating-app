import { readFileSync } from 'node:fs';
import { createApp } from './app.ts';
import { Engine } from './engine.ts';
import { Store } from './store.ts';
import { drainOutbox } from './push.ts';

process.umask(0o077);
const host=process.env.HOST??'127.0.0.1',demo=process.env.DEMO_MODE==='true';
if(demo&&!['127.0.0.1','::1'].includes(host))throw Error('DEMO_MODE requires a loopback listen host');
const cert=process.env.TLS_CERT_FILE,key=process.env.TLS_KEY_FILE;
if(Boolean(cert)!==Boolean(key))throw Error('Set both TLS_CERT_FILE and TLS_KEY_FILE');
if(!['127.0.0.1','::1'].includes(host)&&!cert)throw Error('Non-loopback listening requires TLS certificates; otherwise bind loopback behind HTTPS');
const engine=new Engine(new Store(process.env.DB_PATH??'data/prototype.sqlite'));
const app=await createApp(engine,{demo,...(cert&&key?{tls:{cert:readFileSync(cert,'utf8'),key:readFileSync(key,'utf8')}}:{})});
engine.cleanup();
let draining:Promise<void>|undefined;
const worker=setInterval(()=>{if(draining)return;draining=drainOutbox(engine).catch(()=>{console.error('Outbox worker failed; jobs remain durable');}).finally(()=>{draining=undefined;});},1000);
const cleanup=setInterval(()=>{try{engine.cleanup();}catch{console.error('Cleanup deferred; database maintenance will retry');}},60000);
app.addHook('onClose',async()=>{clearInterval(worker);clearInterval(cleanup);await draining;engine.store.close();});
await app.listen({host,port:Number(process.env.PORT??8787)});
console.log(`Proximity Lab: ${cert?'https':'http'}://${host}:${process.env.PORT??8787} — ${demo?'LOOPBACK SIMULATION ENABLED':'native trials; simulation disabled'}`);
console.log('Physical Bluetooth, notification display, and battery results are unmeasured.');
for(const signal of ['SIGTERM','SIGINT'] as const)process.once(signal,()=>{void app.close();});
